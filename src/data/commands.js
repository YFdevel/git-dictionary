/* фабрики параметров */
const text  = (name, label, example, opts = {}) => ({ name, label, type: 'text', example, required: true, ...opts });
const area  = (name, label, example, opts = {}) => ({ name, label, type: 'text', multiline: true, example, required: true, ...opts });
const raw   = (name, label, example, opts = {}) => ({ name, label, type: 'raw', example, required: true, ...opts });
const num   = (name, label, example, opts = {}) => ({ name, label, type: 'number', example, required: true, ...opts });
const flag  = (name, label, value) => ({ name, label, type: 'flag', value, required: false });
const select = (name, label, options) => ({ name, label, type: 'select', options, required: false });

